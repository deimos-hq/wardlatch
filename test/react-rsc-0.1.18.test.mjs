  const j = JSON.parse(cli(['--paths', code, '--json']).stdout);
  assert.deepEqual(j.results.map((x) => [x.kind, x.status, x.name, x.version, x.file]), [['lockfile', 'EXPOSED', WEBPACK, '19.1.2', a], ['lockfile', 'SAFE', 'next', '16.4.1', a]]);
  assert.equal(j.results[0].fix, pkg(WEBPACK).fix); assert.equal(j.incidents[0].kev, undefined);

  // the clean twin: nothing pinned anywhere. One all-clear whose receipt is the folder walked and each lockfile read.
  const clean = fresh('cli-clean');
  const c1 = put(join(clean, 'blog', 'yarn.lock'), yarn1({ react: '19.1.2' })), c2 = put(join(clean, 'api', 'pnpm-lock.yaml'), pnpm9({ react: '19.1.2' }));
