  const t = spawnSync(process.execPath, ['--require', join(ROOT, 'test', 'support', 'hide-machine-places.cjs'), BIN, '--incident', 'react-rsc-2026-11', '--paths', code, '--json'], { encoding: 'utf8', cwd: app, env: { ...rest, HOME: fresh('norun-home'), PATH: join(app, 'node_modules', '.bin'), WARDLATCH_TEST_OWN_DIR: dir } });
